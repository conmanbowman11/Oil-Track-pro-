-- OilTrack Pro — Migration 001: Filter Sales + Customer Tracking
--
-- HOW TO RUN: Supabase dashboard → SQL Editor → New query →
-- paste this whole file → Run. Safe to run more than once.
--
-- Additive only: adds new tables and new columns (with defaults).
-- Nothing existing is dropped or renamed.
-- =============================================================

-- ─────────────────────────────────────────────
-- 1. Existing tables: new columns
-- ─────────────────────────────────────────────

-- Parts catalog doubles as the filter catalog.
-- markup_pct blank = use the default filter markup from settings.
alter table parts_catalog add column if not exists markup_pct numeric;
alter table parts_catalog add column if not exists active boolean not null default true;

-- Customers: what kind of customer + active/inactive
alter table customers add column if not exists customer_type text not null default 'service';
alter table customers add column if not exists status text not null default 'active';
do $$ begin
  alter table customers add constraint customers_customer_type_chk
    check (customer_type in ('service', 'filter_only', 'both'));
exception when duplicate_object then null; end $$;
do $$ begin
  alter table customers add constraint customers_status_chk
    check (status in ('active', 'inactive'));
exception when duplicate_object then null; end $$;

-- Company settings: filter pricing, filter tax, and the one supplier
alter table company_settings add column if not exists default_filter_markup_pct numeric not null default 30;
alter table company_settings add column if not exists filter_tax_rate_percent numeric not null default 2.5;
alter table company_settings add column if not exists supplier_name text not null default '';
alter table company_settings add column if not exists supplier_contact_name text not null default '';
alter table company_settings add column if not exists supplier_phone text not null default '';
alter table company_settings add column if not exists supplier_email text not null default '';
alter table company_settings add column if not exists supplier_account_number text not null default '';

-- ─────────────────────────────────────────────
-- 2. Customer contacts (several people per customer)
-- ─────────────────────────────────────────────
create table if not exists customer_contacts (
  contact_id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  customer_id uuid not null references customers(customer_id) on delete cascade,
  name text not null default '',
  role text not null default '',
  phone text not null default '',
  email text not null default '',
  is_primary boolean not null default false,
  notes text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists idx_contacts_customer on customer_contacts(customer_id);
-- Only one primary contact per customer
create unique index if not exists uq_contacts_one_primary on customer_contacts(customer_id) where is_primary;

-- ─────────────────────────────────────────────
-- 3. Activities (notes, calls, visits, texts, emails)
-- ─────────────────────────────────────────────
create table if not exists customer_activities (
  activity_id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  customer_id uuid not null references customers(customer_id) on delete cascade,
  contact_id uuid references customer_contacts(contact_id) on delete set null,
  type text not null default 'note' check (type in ('note', 'call', 'visit', 'text', 'email')),
  body text not null default '',
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists idx_activities_customer on customer_activities(customer_id);

-- ─────────────────────────────────────────────
-- 4. Filter orders + line items
-- ─────────────────────────────────────────────
create table if not exists filter_orders (
  filter_order_id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  order_number integer generated by default as identity (start with 1001),
  customer_id uuid not null references customers(customer_id) on delete cascade,
  contact_id uuid references customer_contacts(contact_id) on delete set null,
  status text not null default 'requested'
    check (status in ('requested', 'ordered', 'received', 'delivered', 'paid', 'cancelled')),
  requested_at timestamptz default now(),
  ordered_at timestamptz,
  received_at timestamptz,
  delivered_at timestamptz,
  paid_at timestamptz,
  cancelled_at timestamptz,
  supplier_ref text not null default '',
  notes text not null default '',
  tax_rate_percent numeric not null default 2.5,
  -- Billing: same pattern as work orders (invoice # comes from the shared INV- counter)
  invoice_number integer,
  billed boolean not null default false,
  billed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_filter_orders_customer on filter_orders(customer_id);
create index if not exists idx_filter_orders_status on filter_orders(status);

create table if not exists filter_order_items (
  item_id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  filter_order_id uuid not null references filter_orders(filter_order_id) on delete cascade,
  part_id uuid references parts_catalog(part_id) on delete set null,
  -- Snapshot of the part at the time it was added (old orders never change)
  part_number text not null default '',
  description text not null default '',
  brand text not null default '',
  unit_id uuid references fleet_units(unit_id) on delete set null,
  quantity numeric not null default 1,
  unit_cost numeric not null default 0,
  unit_price numeric not null default 0,
  price_overridden boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_fo_items_order on filter_order_items(filter_order_id);

-- ─────────────────────────────────────────────
-- 5. Filters each machine takes
-- ─────────────────────────────────────────────
create table if not exists equipment_filters (
  equipment_filter_id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  unit_id uuid not null references fleet_units(unit_id) on delete cascade,
  part_id uuid not null references parts_catalog(part_id) on delete cascade,
  quantity_per_change integer not null default 1,
  notes text not null default '',
  created_at timestamptz not null default now(),
  unique (unit_id, part_id)
);
create index if not exists idx_equipment_filters_unit on equipment_filters(unit_id);

-- ─────────────────────────────────────────────
-- 6. Follow-up reminders
-- ─────────────────────────────────────────────
create table if not exists follow_ups (
  follow_up_id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  customer_id uuid not null references customers(customer_id) on delete cascade,
  contact_id uuid references customer_contacts(contact_id) on delete set null,
  title text not null default '',
  notes text not null default '',
  due_date date not null default current_date,
  status text not null default 'open' check (status in ('open', 'done')),
  completed_at timestamptz,
  related_filter_order_id uuid references filter_orders(filter_order_id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists idx_follow_ups_customer on follow_ups(customer_id);
create index if not exists idx_follow_ups_open on follow_ups(status, due_date);

-- ─────────────────────────────────────────────
-- 7. Row Level Security — each user only sees their own rows
--    (same rule as the existing tables: auth.uid() = user_id)
-- ─────────────────────────────────────────────
alter table customer_contacts   enable row level security;
alter table customer_activities enable row level security;
alter table filter_orders       enable row level security;
alter table filter_order_items  enable row level security;
alter table equipment_filters   enable row level security;
alter table follow_ups          enable row level security;

drop policy if exists "Users see own contacts"          on customer_contacts;
drop policy if exists "Users see own activities"        on customer_activities;
drop policy if exists "Users see own filter orders"     on filter_orders;
drop policy if exists "Users see own filter order items" on filter_order_items;
drop policy if exists "Users see own equipment filters" on equipment_filters;
drop policy if exists "Users see own follow ups"        on follow_ups;

create policy "Users see own contacts" on customer_contacts
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users see own activities" on customer_activities
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users see own filter orders" on filter_orders
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users see own filter order items" on filter_order_items
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users see own equipment filters" on equipment_filters
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users see own follow ups" on follow_ups
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ─────────────────────────────────────────────
-- 8. One-time: copy each customer's existing contact into the
--    new Contacts list as their primary contact
-- ─────────────────────────────────────────────
insert into customer_contacts (user_id, customer_id, name, phone, email, is_primary)
select c.user_id, c.customer_id, c.contact_name, coalesce(c.phone, ''), coalesce(c.email, ''), true
from customers c
where coalesce(c.contact_name, '') <> ''
  and c.user_id is not null
  and not exists (select 1 from customer_contacts cc where cc.customer_id = c.customer_id);
